import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tauri = path.join(root, "apps/desktop/src-tauri");
const errors = [];
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const quoted = (text) => [...text.matchAll(/"([^"]+)"/g)].map((match) => match[1]);
const unique = (values) => [...new Set(values)];
const same = (left, right) => left.length === right.length
  && [...left].sort().every((value, index) => value === [...right].sort()[index]);
const checkSet = (label, actual, expected) => {
  if (actual.length !== unique(actual).length) errors.push(`${label}: duplicate entry`);
  if (!same(actual, expected)) {
    errors.push(`${label}: expected [${[...expected].sort().join(", ")}], got [${[...actual].sort().join(", ")}]`);
  }
};

const lib = read("apps/desktop/src-tauri/src/lib.rs");
const handler = lib.match(/tauri::generate_handler!\[([\s\S]*?)\]\)/)?.[1];
if (!handler) errors.push("missing generate_handler! command registry");
const registered = handler
  ? handler.split(",").map((entry) => entry.trim()).filter(Boolean).map((entry) => entry.split("::").at(-1))
  : [];

const build = read("apps/desktop/src-tauri/build.rs");
const manifest = build.match(/const APP_COMMANDS:.*?=\s*&\[([\s\S]*?)\];/)?.[1];
if (!manifest || !build.includes("AppManifest::new().commands(APP_COMMANDS)")) {
  errors.push("build.rs: missing AppManifest backed by APP_COMMANDS");
}
const declared = manifest ? quoted(manifest) : [];
checkSet("AppManifest commands", declared, registered);
const generated = fs.readdirSync(path.join(tauri, "permissions/autogenerated"))
  .filter((file) => file.endsWith(".toml"))
  .map((file) => file.slice(0, -5));
checkSet("generated command permissions", generated, registered);

const permissionList = (file) => {
  const contents = read(file);
  const block = contents.match(/permissions\s*=\s*\[([\s\S]*?)\]/)?.[1];
  if (!block) errors.push(`${file}: missing permissions list`);
  return block ? quoted(block) : [];
};
const allow = (command) => `allow-${command.replaceAll("_", "-")}`;
const importerCommands = [
  "get_appearance",
  "genre_values",
  "lastfm_import_state",
  "lastfm_import_queue",
  "lastfm_import_page",
  "start_lastfm_import",
  "lastfm_import_review",
  "lastfm_import_options",
  "lastfm_import_count_mode",
  "lastfm_import_search_terms",
  "lastfm_import_select_match",
  "lastfm_import_select_matches",
  "lastfm_import_collection_search_albums",
  "lastfm_import_collection_preview_album",
  "lastfm_import_collection_add_album",
  "lastfm_import_collection_remove_album",
  "lastfm_import_activate_collection",
  "lastfm_import_change_track",
  "lastfm_import_change_album",
  "lastfm_import_apply",
  "lastfm_import_retry_apply",
  "lastfm_import_prepare_accept_all",
  "lastfm_import_accept_all",
  "open_external_destination",
];
const sharedImporterCommands = new Set([
  "get_appearance",
  "genre_values",
  "lastfm_import_state",
  "open_external_destination",
]);
const importerOnlyCommands = importerCommands.filter((command) => !sharedImporterCommands.has(command));
checkSet(
  "main command permissions",
  permissionList("apps/desktop/src-tauri/permissions/main.toml"),
  registered.filter((command) => !importerOnlyCommands.includes(command)).map(allow),
);
checkSet(
  "importer command permissions",
  permissionList("apps/desktop/src-tauri/permissions/importer.toml"),
  importerCommands.map(allow),
);
for (const command of importerCommands) {
  if (!registered.includes(command)) errors.push(`importer command is not registered: ${command}`);
}

const capabilityFiles = fs.readdirSync(path.join(tauri, "capabilities")).sort();
checkSet("capability files", capabilityFiles, ["default.json", "lastfm-importer.json"]);
const main = JSON.parse(read("apps/desktop/src-tauri/capabilities/default.json"));
const importer = JSON.parse(read("apps/desktop/src-tauri/capabilities/lastfm-importer.json"));
checkSet("main capability windows", main.windows ?? [], ["main"]);
checkSet("importer capability windows", importer.windows ?? [], ["lastfm-importer"]);
checkSet("main capability platforms", main.platforms ?? [], ["linux", "macOS", "windows"]);
checkSet("importer capability platforms", importer.platforms ?? [], ["linux", "macOS", "windows"]);
checkSet("main capability permissions", main.permissions ?? [], [
  "core:event:allow-listen",
  "core:event:allow-unlisten",
  "core:window:allow-set-title",
  "main-commands",
]);
checkSet("importer capability permissions", importer.permissions ?? [], [
  "core:event:allow-listen",
  "core:event:allow-unlisten",
  "importer-commands",
]);

const config = JSON.parse(read("apps/desktop/src-tauri/tauri.conf.json"));
checkSet("configured capabilities", config.app?.security?.capabilities ?? [], ["default", "lastfm-importer"]);
checkSet("configured window labels", (config.app?.windows ?? []).map((window) => window.label), ["main"]);
const csp = new Set((config.app?.security?.csp ?? "").split(";").map((directive) => directive.trim()));
for (const directive of ["base-uri 'none'", "object-src 'none'", "frame-src 'none'", "form-action 'none'"]) {
  if (!csp.has(directive)) errors.push(`missing CSP directive: ${directive}`);
}
const allCapabilityPermissions = [...(main.permissions ?? []), ...(importer.permissions ?? [])];
for (const forbidden of [":default", "allow-emit", "allow-image-from-path", "allow-reveal-item-in-dir"]) {
  if (allCapabilityPermissions.some((permission) => permission.includes(forbidden))) {
    errors.push(`forbidden capability permission: ${forbidden}`);
  }
}
if (registered.includes("import_local")) errors.push("path-bearing import_local command remains registered");
for (const file of fs.readdirSync(path.join(root, "apps/desktop/src"), { recursive: true })) {
  if (!/\.(?:ts|tsx)$/.test(file)) continue;
  const contents = read(path.join("apps/desktop/src", file));
  if (file !== "ipc.ts" && contents.includes("@tauri-apps/api/core")) {
    errors.push(`raw Tauri core import outside ipc.ts: ${file}`);
  }
  if (/["']import_local["']/.test(contents)) {
    errors.push(`frontend path-bearing import_local invoke remains: ${file}`);
  }
}
for (const file of fs.readdirSync(path.join(tauri, "src"), { recursive: true })) {
  if (!file.endsWith(".rs")) continue;
  const contents = read(path.join("apps/desktop/src-tauri/src", file));
  if (/\.emit\(\s*"/.test(contents)) {
    errors.push(`global Tauri event emission remains: ${file}`);
  }
  for (const event of ["player-state", "playback-authorization-required", "operation-error", "operation-recovered", "local-import-complete", "startup-notice"]) {
    if (contents.includes(`emit_main(app, "${event}"`) || contents.includes(`emit_main(&app, "${event}"`)) {
      errors.push(`sensitive core event emission remains: ${file}: ${event}`);
    }
  }
}
for (const event of ["connection-changed", "lastfm-changed"]) {
  const safe = new RegExp(`emit_main\\([^;]*?"${event}"\\s*,\\s*\\(\\)\\s*\\)`, "s");
  if (!safe.test(lib)) errors.push(`sensitive invalidation carries or may carry a payload: ${event}`);
}
for (const command of ["subscribe_main_events", "unsubscribe_main_events"]) {
  if (importerCommands.includes(command)) errors.push(`private main channel granted to importer: ${command}`);
  if (!permissionList("apps/desktop/src-tauri/permissions/main.toml").includes(allow(command))) {
    errors.push(`private main channel missing main permission: ${command}`);
  }
}
for (const file of fs.readdirSync(path.join(root, "apps/desktop/src"), { recursive: true })) {
  if (!/\.(?:ts|tsx)$/.test(file)) continue;
  const contents = read(path.join("apps/desktop/src", file));
  for (const event of ["player-state", "playback-authorization-required", "operation-error", "operation-recovered", "local-import-complete", "startup-notice"]) {
    if (contents.includes(`listen('${event}'`) || contents.includes(`listen(\"${event}\"`)) {
      errors.push(`sensitive core event listener remains: ${file}: ${event}`);
    }
  }
}

if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}
console.log(`Tauri ACL checks passed (${registered.length} application commands).`);
